// Daily puzzle generation with a free Groq model.
// The model is asked for a strict JSON format; everything it returns is validated and
// cleaned before it is stored. Any failure falls back to the built-in classic pool.
import { TIERS, normalize, etDate } from '../public/rules.mjs';
import { dayNumber, storedPuzzle, savePuzzle, addDays } from './puzzles.mjs';
import { CLASSIC } from './content/classic.mjs';

export const TIER_ORDER = ['plankton', 'tooclever', 'schooler', 'rare', 'deepcut', 'krillion'];
const GROQ_URL = 'https://api.groq.com/openai/v1/chat/completions';

export function instructions(avoid) {
  return `You write one prompt for SourceKrillion, a rare-answer trivia game.
Players see a category prompt and type ONE answer. Common answers score little; rare but valid answers score a lot.

Return ONLY a JSON object in exactly this format:
{"text":"Name a ...","answers":{"plankton":["..."],"tooclever":["..."],"schooler":["..."],"rare":["..."],"deepcut":["..."],"krillion":["..."]}}

Rules:
- "text" starts with "Name a" or "Name an" and is under 90 characters.
- Use a category with a finite, checkable set of correct answers (countries, elements, films by a director, dog breeds, ...).
- List as many valid answers as you can: aim for 30 to 80, at least 15. Be factually accurate; never invent answers.
- Tiers by how often an average English-speaking adult would say it first:
  plankton = the 3-6 answers almost everyone says; schooler = well known; rare = uncommon;
  deepcut = obscure but real; krillion = the 1-5 most obscure valid answers.
  tooclever = 0-2 "smart" answers that everyone thinks is obscure (may be empty).
- Put spelling variants or short names after a slash in the same string, e.g. "United Kingdom/UK/Britain".
- No answer may appear twice.
- Pick a topic different from all of these: ${avoid.slice(0, 150).map(t => JSON.stringify(t)).join(', ')}`;
}
const TOPICS = ['geography', 'science and nature', 'film and television', 'music', 'sport', 'food and drink', 'words and language', 'history', 'animals', 'art and literature', 'space', 'technology'];

// Turn whatever the model sent into a clean puzzle, or throw.
export function cleanGenerated(raw, date, env, need = 7) {
  let data = raw;
  if (typeof raw === 'string') {
    const start = raw.indexOf('{'), end = raw.lastIndexOf('}');
    data = JSON.parse(raw.slice(start, end + 1));
  }
  const list = Array.isArray(data?.prompts) ? data.prompts : data?.text ? [data] : [];
  const prompts = [], seenText = new Set();
  for (const item of list) {
    const text = String(item?.text || '').replace(/\s+/g, ' ').trim().slice(0, 120);
    if (!/^name an? /i.test(text) || seenText.has(normalize(text))) continue;
    const seen = new Set(), answers = [];
    for (const tier of TIER_ORDER) {
      const entries = Array.isArray(item.answers?.[tier]) ? item.answers[tier] : [];
      for (const entry of entries.slice(0, 200)) {
        const [answer, ...aliases] = String(entry).split('/').map(s => s.trim().slice(0, 80)).filter(Boolean);
        if (!answer) continue;
        const keys = [answer, ...aliases].map(normalize).filter(Boolean);
        if (!keys.length || keys.some(k => seen.has(k))) continue;
        keys.forEach(k => seen.add(k));
        answers.push(aliases.length ? { answer, tier, aliases: [...new Set(aliases)].slice(0, 6) } : { answer, tier });
      }
    }
    const tiers = new Set(answers.map(a => a.tier));
    if (answers.length < 15 || !tiers.has('plankton') || !tiers.has('krillion') || tiers.size < 4) continue;
    seenText.add(normalize(text));
    prompts.push({ id: `g${date}-${prompts.length + 1}`, text, answers });
    if (prompts.length === need) break;
  }
  if (prompts.length !== need) throw new Error(`Generated puzzle had ${prompts.length} usable prompts`);
  return { date, dayNumber: dayNumber(env, date), source: `Generated by ${env.GROQ_MODEL || 'openai/gpt-oss-120b'}`, prompts };
}

async function recentTexts(env) {
  const rows = (await env.DB.prepare('SELECT content FROM puzzles ORDER BY date DESC LIMIT 30').all()).results;
  return [...rows.flatMap(r => JSON.parse(r.content).prompts.map(p => p.text)), ...CLASSIC.map(p => p.text)];
}

const pause = ms => new Promise(r => setTimeout(r, ms));
async function askOne(env, avoid, topic, fetchImpl) {
  const model = env.GROQ_MODEL || 'openai/gpt-oss-120b';
  const body = JSON.stringify({
    model,
    messages: [{ role: 'system', content: instructions(avoid) }, { role: 'user', content: `Write one prompt about ${topic}. JSON only.` }],
    response_format: { type: 'json_object' },
    temperature: 0.9,
    max_completion_tokens: 5000, // Groq's free tier counts this against 8,000 tokens per minute
    ...(model.includes('gpt-oss') ? { reasoning_effort: 'low' } : {}),
  });
  for (let attempt = 0; attempt < 3; attempt++) {
    const response = await fetchImpl(GROQ_URL, { method: 'POST', headers: { 'Content-Type': 'application/json', Authorization: `Bearer ${env.GROQ_API_KEY}` }, body, signal: AbortSignal.timeout(120000) });
    if (response.status === 429) { await pause(Math.min(90, Number(response.headers.get('retry-after')) || 30) * 1000 * (env.GENERATE_PAUSE === '0' ? 0 : 1)); continue; }
    if (!response.ok) throw new Error(`Groq returned ${response.status}: ${(await response.text()).slice(0, 200)}`);
    return (await response.json()).choices?.[0]?.message?.content || '';
  }
  throw new Error('Groq kept rate-limiting the request');
}

// Seven prompts, one request each, spaced out so the free tier's per-minute limit is never hit.
export async function generatePuzzle(env, date, fetchImpl = fetch) {
  if (!env.GROQ_API_KEY) throw new Error('GROQ_API_KEY is not set');
  const avoid = await recentTexts(env), prompts = [], gap = env.GENERATE_PAUSE === '0' ? 0 : 40000;
  const topics = [...TOPICS].sort(() => Math.random() - .5);
  for (let attempt = 0; prompts.length < 7 && attempt < 11; attempt++) {
    if (attempt) await pause(gap);
    try {
      const [p] = cleanGenerated(await askOne(env, [...prompts.map(p => p.text), ...avoid], topics[attempt % topics.length], fetchImpl), date, env, 1).prompts;
      if (prompts.some(q => normalize(q.text) === normalize(p.text))) continue;
      prompts.push({ ...p, id: `g${date}-${prompts.length + 1}` });
    } catch (e) { if (/GROQ_API_KEY|401|403/.test(e.message)) throw e; }
  }
  if (prompts.length !== 7) throw new Error(`Only ${prompts.length} of 7 prompts generated`);
  return { date, dayNumber: dayNumber(env, date), source: `Generated by ${env.GROQ_MODEL || 'openai/gpt-oss-120b'}`, prompts };
}

// Make sure a generated puzzle exists for `date`. Never overwrites a day that was already served.
export async function ensureGenerated(env, date, fetchImpl = fetch) {
  if (await storedPuzzle(env, date)) return { date, status: 'exists' };
  const attempts = (await env.DB.prepare('SELECT COUNT(*) AS n FROM generation_log WHERE date=? AND attempt_at>?').bind(date, Date.now() - 6 * 3600000).first()).n;
  if (attempts >= 3) return { date, status: 'backoff' };
  try {
    const puzzle = await generatePuzzle(env, date, fetchImpl);
    await savePuzzle(env, puzzle);
    await env.DB.prepare('INSERT INTO generation_log(date,attempt_at,ok,detail) VALUES(?,?,1,?)').bind(date, Date.now(), puzzle.source).run();
    return { date, status: 'generated' };
  } catch (e) {
    await env.DB.prepare('INSERT INTO generation_log(date,attempt_at,ok,detail) VALUES(?,?,0,?)').bind(date, Date.now(), String(e.message).slice(0, 300)).run();
    return { date, status: 'failed', error: e.message };
  }
}

// Runs every few minutes: prepares tomorrow ahead of New York midnight (and today if missing).
export async function dailyJob(env, fetchImpl = fetch) {
  if (!env.GROQ_API_KEY) return [];
  const today = etDate();
  const out = [];
  if (!(await storedPuzzle(env, today))) out.push(await ensureGenerated(env, today, fetchImpl));
  out.push(await ensureGenerated(env, addDays(today, 1), fetchImpl));
  return out;
}
